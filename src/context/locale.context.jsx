const LocaleContext = createContext(null);

export const LocaleProvider = ({ children }) => {
  const location = useLocation();
  const navigate = useNavigate();
  const routeLocale = location.pathname.split("/")[1];
  const [locale, setLocaleState] = useState(
    routeLocale === "en" || routeLocale === "vi"
      ? routeLocale
      : localStorage.getItem("shop_locale") || "vi"
  );

  useEffect(() => {
    if (routeLocale === "en" || routeLocale === "vi") {
      setLocaleState(routeLocale);
      localStorage.setItem("shop_locale", routeLocale);
    }
  }, [routeLocale]);

  useEffect(() => {
    document.documentElement.lang = locale;
    document.title =
      locale === "vi"
        ? "JagerTheJager Shop | Sản phẩm cho cuộc vui đúng điệu"
        : "JagerTheJager Shop | Own the night responsibly";

    const description =
      locale === "vi"
        ? "Khám phá sản phẩm JagerTheJager Shop, giao hàng tại TP. Hồ Chí Minh."
        : "Discover JagerTheJager Shop products with delivery in Ho Chi Minh City.";
    document.querySelector('meta[name="description"]')?.setAttribute("content", description);

    const localizedSuffix = location.pathname.replace(/^\/(vi|en)/, "") || "";
    const canonical = document.querySelector('link[rel="canonical"]');
    if (canonical) canonical.href = `${window.location.origin}/${locale}${localizedSuffix}${location.search}`;
    document
      .querySelector('link[hreflang="vi"]')
      ?.setAttribute("href", `${window.location.origin}/vi${localizedSuffix}`);
    document
      .querySelector('link[hreflang="en"]')
      ?.setAttribute("href", `${window.location.origin}/en${localizedSuffix}`);
  }, [locale, location.pathname, location.search]);

  const setLocale = (nextLocale) => {
    const parts = location.pathname.split("/");
    if (parts[1] === "vi" || parts[1] === "en") parts[1] = nextLocale;
    else parts.splice(1, 0, nextLocale);
    navigate(`${parts.join("/")}${location.search}`);
  };

  const value = useMemo(
    () => ({
      locale,
      setLocale,
      t: (key) => translations[locale][key] || key,
      localize: (path = "/") => `/${locale}${path === "/" ? "" : path}`,
    }),
    [locale, location.pathname, location.search]
  );

  return <LocaleContext.Provider value={value}>{children}</LocaleContext.Provider>;
};

export const useLocale = () => useContext(LocaleContext);
